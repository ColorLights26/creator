#!/usr/bin/env python3
"""Compile the waveform Metal renderer for real and compare it with the Flutter painter.

`xcrun metal` is not required: the production renderer compiles its shader with
`device.makeLibrary(source:)`, so instantiating the class on the Mac GPU is the real
Metal compilation. The renderer, its layer/state types and the output allocator are
extracted from the canonical Swift by regex, exactly like check_creator_scenes.py;
nothing in production changes. Only harness-side adjustments are applied to the
extracted copy: `private` is dropped from the renderer class so the test file can see
it, the class is renamed so a baseline revision can live in the same binary, and an
extension (same generated file, hence allowed to use the private setters) injects a
controlled signal into the real SceneRenderV2WaveformState.

Goldens come from `audiovisuals/test/music_waveform_test.dart` run with
MUSIC_WAVEFORM_GOLDEN_DIR set (raw premultiplied RGBA + JSON per case).
"""
import argparse
import re
import subprocess
import sys
import time
from pathlib import Path


def extract(source, pattern, what):
    match = re.search(pattern, source, re.S | re.M)
    if not match:
        raise RuntimeError(f'{what} not found in source')
    return match.group()


def renderer(source, name):
    text = extract(
        source,
        r'@available\(iOS 15\.0, \*\)\nprivate final class SceneRenderV2WaveformMetalRenderer \{.*?^\}',
        'waveform renderer',
    )
    # Harness visibility only: the class stays private in production.
    text = text.replace('private final class', 'final class', 1)
    return text.replace('SceneRenderV2WaveformMetalRenderer', name)


def constant(source, name, alias):
    text = extract(source, r'private static let ' + name + r' = \[.*?\]', name)
    return text.replace('private static let ' + name, 'let ' + alias, 1)


def run(command, timeout, log):
    log.write('$ ' + ' '.join(command) + '\n')
    log.flush()
    started = time.monotonic()
    completed = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    log.write(completed.stdout)
    log.write(completed.stderr)
    log.write(f'exit={completed.returncode} ({time.monotonic() - started:.1f}s)\n')
    log.flush()
    sys.stdout.write(completed.stdout)
    sys.stderr.write(completed.stderr)
    if completed.returncode != 0:
        raise RuntimeError(f'{command[0]} failed with exit {completed.returncode}')


def main():
    package = Path(__file__).resolve().parents[2]
    runtime = package / 'ios/Classes/Runtime'
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source', default=str(runtime / 'SceneRenderV2ImageSurface.swift'),
                        help='Swift file holding the candidate renderer (default: canonical runtime)')
    parser.add_argument('--baseline', help='Optional earlier revision of the same Swift file to compare cost/parity against')
    parser.add_argument('--golden', required=True, help='Directory with <case>.json/.rgba exported by music_waveform_test.dart')
    parser.add_argument('--output', required=True, help='Receipts: compile log, renders, parity.txt, cost.txt')
    parser.add_argument('--frames', type=int, default=200, help='Timed frames per cost case (>= 200)')
    args = parser.parse_args()

    output = Path(args.output).resolve()
    build = output / 'build'
    build.mkdir(parents=True, exist_ok=True)
    source = Path(args.source).read_text()
    parts = [
        'import Foundation', 'import Metal', 'import CoreGraphics', '',
        '// Generated by check_waveform_renderer.py from ' + str(Path(args.source).resolve()), '',
        extract(source, r'^struct SceneRenderV2WaveformLayer \{.*?^\}', 'waveform layer'),
        extract(source, r'^final class SceneRenderV2WaveformState \{.*?^\}', 'waveform state'),
        extract(source, r'@available\(iOS 15\.0, \*\)\n(?:private )?final class SceneSurfaceNativeOutputAllocator \{.*?^\}', 'output allocator'),
        constant(source, 'waveformRenderScales', 'harnessWaveformRenderScales'),
        constant(source, 'waveformSampleCounts', 'harnessWaveformSampleCounts'),
        constant(source, 'waveformGlowPasses', 'harnessWaveformGlowPasses'),
        renderer(source, 'WaveformRendererCandidate'),
    ]
    flags = []
    if args.baseline:
        baseline = Path(args.baseline).read_text()
        parts.append('// Baseline renderer from ' + str(Path(args.baseline).resolve()))
        parts.append(renderer(baseline, 'WaveformRendererBaseline'))
        parts.append('extension WaveformRendererBaseline: WaveformRendering {}')
        flags = ['-D', 'HAS_BASELINE']
    parts.append('extension WaveformRendererCandidate: WaveformRendering {}')
    parts.append('''extension SceneRenderV2WaveformState {
  /// Harness only: the renderer reads exactly these five values. Same file as the
  /// class, so the production `private(set)` stays private.
  func inject(samples: [Float], lineEnergy: Double, peakAmplitude: Double,
              impactLight: Double, lineVisibility: Double) {
    self.samples = samples
    self.lineEnergy = lineEnergy
    self.peakAmplitude = peakAmplitude
    self.impactLight = impactLight
    self.lineVisibility = lineVisibility
  }
}''')
    generated = build / 'Generated.swift'
    generated.write_text('\n\n'.join(parts) + '\n')
    executable = build / 'waveform-renderer-tests'
    with open(output / 'compile-metal.txt', 'w') as log:
        log.write(f'# Swift + embedded Metal compilation of the waveform renderer\n')
        log.write(f'source: {Path(args.source).resolve()}\n')
        if args.baseline:
            log.write(f'baseline: {Path(args.baseline).resolve()}\n')
        log.write(f'generated: {generated}\n\n')
        run(['xcrun', 'swiftc', '--version'], 60, log)
        run(['xcrun', 'swiftc', '-O', *flags, '-o', str(executable), str(generated),
             str(runtime / 'SceneRenderSignalFrameV2.swift'),
             str(package / 'ios/Tests/waveform_renderer_tests.swift')], 300, log)
        # Instantiating each renderer runs device.makeLibrary(source:): the real
        # Metal compile. The binary prints the device and the compile time.
        run([str(executable), str(Path(args.golden).resolve()), str(output), str(args.frames)],
            600 + 5 * args.frames, log)


if __name__ == '__main__':
    main()
