private func neonModulo(_ value: Double, _ divisor: Double) -> Double {
  let remainder = value.truncatingRemainder(dividingBy: divisor)
  return remainder < 0 ? remainder + abs(divisor) : remainder
}
private func _fract(_ value: Double) -> Double { value - floor(value) }
private func _smoothstep(_ edge0: Double, _ edge1: Double, _ value: Double) -> Double {
  let t = neonClamp((value - edge0) / (edge1 - edge0), 0, 1)
  return t * t * (3 - 2 * t)
}

