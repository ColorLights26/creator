// Reactiva · Cinta de Seda — transparencia momentánea. Con el golpe una cinta ancha de
// seda de luz esmeralda se despliega de lado a lado de la escena, ondeando en
// una S: los pliegues giran y atrapan la luz en brillos blancos estrechos que
// corren por la tela, el cuerpo es verde saturado con su degradado y el filo
// brilla. Ya está medio desplegada en el golpe y se va estrechando hasta
// desaparecer. Sólo suma luz. Referente: seda líquida en movimiento.
// Funciona encima de cualquier escena sin conocerla: sólo luz, sin objetos que
// se queden. Sin música no dibuja nada. Nunca más de tres destellos por segundo.
// Su detalle sale de una textura propia de alta calidad que el shader anima.
import 'package:scene_compositor/authoring.dart';

// Ajustes propios de este visual. Studio los muestra en Ajustes.
const modifiers = [
  CreatorModifier.choice('disparo', 'Lo dispara', options: ['Golpe grande', 'Cada frase', 'Subida de energía']),
  // FORMA: ancho de la cinta.
  CreatorModifier.slider('ancho', 'Ancho de la cinta', min: .6, max: 1.5, value: 1),
  // MOVIMIENTO: cuánto dura.
  CreatorModifier.slider('caida', 'Duración', min: .6, max: 1.8, value: 1.1),
];

